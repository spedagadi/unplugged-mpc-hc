# gen_omdb_key.ps1 -- emit omdb_key_generated.h from the UNTRACKED _omdb_key.py.
#
# Why a generated header: the shipped key must not sit in the payload as a plain
# file (1.3.0 shipped _internal\mpvprocessor\media\_omdb_key.py, readable by
# anyone with the installer). Compiling masked bytes into the exe means no
# plaintext key exists in the payload and `strings`/a hex search finds nothing.
#
# What this is NOT: secrecy. The mask lives in the same binary, so a debugger or
# a memory dump recovers the key. Obfuscation only defeats casual extraction.
# If the key must genuinely stay secret, put a proxy in front of OMDb.
#
# The header is regenerated on every build, so it is never committed (the key is
# not in the public repo) and the mask differs run to run.
param(
  [string]$KeyFile = (Join-Path $PSScriptRoot '..\..\src\unplugged-ui\src\mpvprocessor\media\_omdb_key.py'),
  [string]$Out     = (Join-Path $PSScriptRoot 'omdb_key_generated.h')
)
$ErrorActionPreference = 'Stop'

$key = ''
if (Test-Path -LiteralPath $KeyFile) {
  $text = Get-Content -LiteralPath $KeyFile -Raw
  $m = [regex]::Match($text, 'OMDB_API_KEY\s*=\s*["'']([^"'']+)["'']')
  if ($m.Success) { $key = $m.Groups[1].Value }
}

$bytes = [Text.Encoding]::ASCII.GetBytes($key)
$n = $bytes.Length
$rng = [Security.Cryptography.RandomNumberGenerator]::Create()
$mask   = New-Object byte[] ([Math]::Max($n, 1))
$masked = New-Object byte[] ([Math]::Max($n, 1))
if ($n -gt 0) {
  $rng.GetBytes($mask)
  for ($i = 0; $i -lt $n; $i++) {
    $roll = ($i * 37) -band 0xFF
    $masked[$i] = $bytes[$i] -bxor $mask[$i] -bxor $roll
  }
}

function Emit([string]$name, [byte[]]$arr) {
  $vals = ($arr | ForEach-Object { '0x{0:X2}' -f $_ }) -join ','
  return "static const unsigned char $name[] = { $vals };"
}

$h = @()
$h += '// GENERATED by gen_omdb_key.ps1. DO NOT COMMIT: it carries the key.'
$h += '#pragma once'
$h += '// Masked bytes + independent random mask. No plaintext in the binary, but a'
$h += '// debugger/memory dump still recovers it: obfuscation, not secrecy.'
$h += (Emit 'kOmdbKeyMasked' $masked)
$h += (Emit 'kOmdbKeyMask'   $mask)
$h += "static const int kOmdbKeyLen = $n;"
Set-Content -LiteralPath $Out -Value ($h -join "`r`n") -Encoding ASCII
Write-Host ("embedded OMDb key: {0} byte(s) -> {1}" -f $n, $Out)